const DICTS: Record<Language, Dict> = { ru, en, fr, es, de };

export function translate(language: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  let str = DICTS[language]?.[key] ?? DICTS.ru[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(`{${k}}`, String(v));
    }
  }
  return str;
}

export function pluralForKey(language: Language, n: number, one: TranslationKey, few: TranslationKey, many: TranslationKey): string {
  if (language === 'ru') {
    const mod10 = n % 10;
    const mod100 = n % 100;
    if (mod10 === 1 && mod100 !== 11) return translate(language, one);
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return translate(language, few);
    return translate(language, many);
  }
  return n === 1 ? translate(language, one) : translate(language, many);
}

// Region codes for the profile's region picker. Falls back to a curated
// list if the runtime doesn't support Intl.supportedValuesOf (older Node).
export function getRegionCodes(): string[] {
  try {
    const supportedValuesOf = Intl.supportedValuesOf as ((key: string) => string[]) | undefined;
    if (typeof supportedValuesOf === 'function') {
      return supportedValuesOf('region').filter((r: string) => /^[A-Z]{2}$/.test(r));
    }
  } catch {
    // fall through to curated list
  }
  return ['US', 'GB', 'RU', 'DE', 'FR', 'ES', 'IT', 'BR', 'MX', 'JP', 'KR', 'IN', 'CA', 'AU', 'NL', 'SE', 'PL', 'TR', 'UA', 'PT'];
}

const LOCALE_MAP: Record<Language, string> = {
  ru: 'ru-RU', en: 'en-US', fr: 'fr-FR', es: 'es-ES', de: 'de-DE',
};

export function toLocale(language: Language): string {
  return LOCALE_MAP[language];
}

export function regionDisplayName(code: string, language: Language): string {
  try {
    return new Intl.DisplayNames([language], { type: 'region' }).of(code) ?? code;
  } catch {
    return code;
  }
}
